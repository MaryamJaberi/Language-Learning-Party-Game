export function resolveUiLang(lang: Language | string): Language {
  if (lang === 'en-US') return 'en' as Language;
  return (lang as Language) || 'en';
}

export function isRtlLang(lang: Language | string): boolean {
  return lang === 'fa' || lang === 'ar' || lang === 'ur' || lang === 'he' || lang === 'ku';
}

