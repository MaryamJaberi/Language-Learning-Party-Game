export function tUI(lang: Language | string): any {
  const code = resolveUiLang(lang as Language);
  const base = TRANSLATIONS[code] || TRANSLATIONS.en || {};
  const extra = UI_STRINGS[code] || {};

  // Smart derivation: bridge any missing key from base to extra so standard terms are localized
  const derived: Record<string, any> = {};
  if (!extra.startNewGame && (base.newGame || base.start)) derived.startNewGame = base.newGame || base.start;
  if (!extra.setup && base.setup) derived.setup = base.setup;
  if (!extra.guide && (base.guide || base.rules)) derived.guide = base.guide || base.rules;
  if (!extra.history && base.history) derived.history = base.history;
  if (!extra.players && base.players) derived.players = base.players;
  if (!extra.rounds && base.rounds) derived.rounds = base.rounds;
  if (!extra.team && base.team) derived.team = base.team;
  if (!extra.teams && (base.teams || base.team)) derived.teams = base.teams || base.team;
  if (!extra.close && base.exit) derived.close = base.exit;
  if (!extra.winner && base.winner) derived.winner = base.winner;
  if (!extra.round && base.round) derived.round = base.round;
  if (!extra.score && (base.totalScore || base.score)) derived.score = base.totalScore || base.score;
  if (!extra.accuracy && base.accuracyLabel) derived.accuracy = base.accuracyLabel;
  if (!extra.playAgain && base.playAgain) derived.playAgain = base.playAgain;
  if (!extra.returnMenu && base.returnMenu) derived.returnMenu = base.returnMenu;
  if (!extra.vocabParty && base.subtitle) derived.vocabParty = base.subtitle;
  if (!extra.tagline && base.subtitle) derived.tagline = base.subtitle;
  if (!extra.singlePlayerBtn && base.singlePlayer) derived.singlePlayerBtn = base.singlePlayer;
  if (!extra.onlineRoom && base.onlineRoom) derived.onlineRoom = base.onlineRoom;

  return {
    ...TRANSLATIONS.en,
    ...UI_STRINGS.en,
    ...base,
    ...derived,
    ...extra
  };
}

export function toPersianDigits(str: string | number): string {
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(str).replace(/[0-9]/g, (w) => persianDigits[+w]);
}

export function tf(lang: Language | string, key: string, vars?: Record<string, string | number>): string {
  const pack = tUI(lang);
  let s = (pack[key] as string) || (UI_STRINGS.en && UI_STRINGS.en[key]) || key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => {
      const val = vars[k] ?? '';
      if (lang === 'fa' && (typeof val === 'number' || /^\d+$/.test(String(val)))) {
        return toPersianDigits(val);
      }
      return String(val);
    });
  }
  return s;
}

export function getTeamName(colorOrIndex: string | number, lang: Language | string): string {
  const pack = tUI(lang);
  const colorMap: Record<string, string> = pack.teamNames || {
    BLUE: 'Blue',
    RED: 'Red',
    GREEN: 'Green',
    YELLOW: 'Yellow'
  };
  const teamWord = pack.team || 'Team';
  
  if (typeof colorOrIndex === 'number') {
    const colors = ['BLUE', 'RED', 'GREEN', 'YELLOW'];
    const c = colors[colorOrIndex % colors.length];
    const localizedColor = colorMap[c] || c;
    return `${teamWord} ${localizedColor}`;
  }
  
  const c = String(colorOrIndex).toUpperCase();
  const localizedColor = colorMap[c] || c;
  return `${teamWord} ${localizedColor}`;
}
